#!/usr/bin/env python3
"""Build the reference book with Python 3.9+ and Tectonic or XeLaTeX."""

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
TEMPLATE = ROOT / "teambook"
BUILD = ROOT / "build" / "teambook"
LANGUAGES = {
    ".cpp": "C++", ".cc": "C++", ".cxx": "C++", ".h": "C++", ".hpp": "C++",
    ".py": "Python", ".java": "Java", ".rs": "", ".txt": "",
}
TEX_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex_escape(text):
    return "".join(TEX_ESCAPES.get(char, char) for char in text)


def revision():
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
            capture_output=True, text=True, check=True,
        )
        return "commit " + result.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "local sources"


def generate():
    config = json.loads((TEMPLATE / "config.json").read_text(encoding="utf-8"))
    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "snippets").mkdir(exist_ok=True)
    for name in ("main.tex", "preamble.tex"):
        shutil.copyfile(TEMPLATE / name, BUILD / name)

    contents = ["% Generated by build.py; edit the original algorithm files instead."]
    manifest = []
    seen = set()
    for section in config["sections"]:
        directory = (ROOT / section["directory"]).resolve()
        if not directory.is_relative_to(ROOT) or not directory.is_dir():
            raise ValueError("Invalid section directory: " + section["directory"])
        sources = sorted(
            (p for p in directory.rglob("*") if p.suffix.lower() in LANGUAGES and p.is_file()),
            key=lambda p: (p.relative_to(directory).as_posix().casefold(), p.as_posix()),
        )
        if not sources:
            raise ValueError("Section has no source files: " + section["directory"])
        contents.append(r"\section{" + tex_escape(section["title"]) + "}")
        for source in sources:
            if not source.resolve().is_relative_to(ROOT):
                raise ValueError("Source points outside repository: " + str(source))
            relative = source.relative_to(ROOT).as_posix()
            if relative in seen:
                raise ValueError("Source included twice: " + relative)
            seen.add(relative)
            # ASCII staging names avoid TeX filename issues (spaces, apostrophes, &).
            snippet = "snippets/{:03d}{}".format(len(manifest) + 1, source.suffix.lower())
            text = source.read_text(encoding="utf-8-sig")
            (BUILD / snippet).write_text(text, encoding="utf-8")
            title = source.relative_to(directory).with_suffix("").as_posix()
            contents.extend([
                r"\subsection{" + tex_escape(title) + "}",
                r"{\fontsize{6}{7}\selectfont\ttfamily " + tex_escape(relative) + r"\par}",
                r"\lstinputlisting[language={" + LANGUAGES[source.suffix.lower()]
                + "}]{" + snippet + "}",
            ])
            manifest.append({"source": relative, "listing": snippet})

    metadata = [
        r"\newcommand{\TeamBookTitle}{" + tex_escape(config["title"]) + "}",
        r"\newcommand{\TeamBookSubtitle}{" + tex_escape(config["subtitle"]) + "}",
        r"\newcommand{\TeamBookRevision}{" + tex_escape(revision()) + "}",
        r"\newcommand{\TeamBookFileCount}{" + str(len(manifest)) + "}",
    ]
    (BUILD / "metadata.tex").write_text("\n".join(metadata) + "\n", encoding="utf-8")
    (BUILD / "contents.tex").write_text("\n".join(contents) + "\n", encoding="utf-8")
    (BUILD / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
    )
    print("Generated {} listings in {}".format(len(manifest), BUILD), flush=True)


def find_engine(requested):
    candidates = ("tectonic", "xelatex") if requested == "auto" else (requested,)
    for candidate in candidates:
        executable = shutil.which(candidate)
        if executable:
            return candidate, executable
    raise ValueError(
        "LaTeX compiler not found. Install Tectonic (https://tectonic-typesetting.github.io/) "
        "or XeLaTeX (TeX Live / MiKTeX), then add it to PATH. "
        "Use --generate-only to prepare the LaTeX sources without a compiler."
    )


def compile_pdf(engine, executable):
    if engine == "tectonic":
        command = [executable, "--keep-logs", "--keep-intermediates", "main.tex"]
        passes = 1  # Tectonic automatically reruns TeX until references settle.
    else:
        command = [executable, "-interaction=nonstopmode", "-halt-on-error",
                   "-file-line-error", "-no-shell-escape", "main.tex"]
        passes = 3  # Populate the table of contents, then stabilize its page numbers.
    with (BUILD / "build.log").open("w", encoding="utf-8") as log:
        for _ in range(passes):
            result = subprocess.run(command, cwd=BUILD, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, encoding="utf-8", errors="replace")
            log.write(result.stdout)
            log.flush()
            if result.returncode:
                print(result.stdout[-8000:], file=sys.stderr)
                raise ValueError("LaTeX failed; full output: " + str(BUILD / "build.log"))
    if not (BUILD / "main.pdf").is_file():
        raise ValueError("Compiler finished without producing main.pdf")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-only", action="store_true", help="prepare standalone LaTeX sources only")
    parser.add_argument("--engine", choices=("auto", "tectonic", "xelatex"), default="auto")
    parser.add_argument("--output", type=Path, default=ROOT / "teambook.pdf", help="destination PDF")
    args = parser.parse_args()
    try:
        generate()
        if not args.generate_only:
            engine, executable = find_engine(args.engine)
            print("Compiling with " + engine + "...", flush=True)
            compile_pdf(engine, executable)
            output = args.output.expanduser().resolve()
            output.parent.mkdir(parents=True, exist_ok=True)
            if output != BUILD / "main.pdf":
                shutil.copyfile(BUILD / "main.pdf", output)
            print("PDF: " + str(output))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print("Error: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
